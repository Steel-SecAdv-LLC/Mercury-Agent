"""Build the served Mercury Console from the design prototype, verbatim.

The prototype (``docs/design/mercury_console/design/Mercury CLI.dc.html``) is
the source of truth for layout, copy, styling and behaviour. It runs on a
design-tool runtime (``support.js``: React plus ``new Function``) that the
page CSP forbids, and its template carries inline ``style`` attributes. This
script keeps the prototype's template, logic class and modules unchanged and
replaces only what the CSP and a real same-origin server require:

* the template is precompiled into a JSON tree (``template.js``), so the
  browser never parses markup containing ``style=``; ``dc-runtime.js``
  renders it with CSSOM style writes, which CSP permits;
* ``style-hover``/``style-focus`` attributes become static class rules in
  ``port.css`` (the prototype generated the same rules at runtime);
* the logic class is wrapped as a plain script (``logic.js``) instead of
  being ``eval``'d;
* the design-system tokens ship without their Google-Fonts ``@import``;
* images are served from ``/static/console/``.

Every textual patch is listed in :data:`LOGIC_PATCHES` / :data:`MODULE_PATCHES`
and must apply exactly once, so the build fails loudly if the prototype moves.

Usage::

    python scripts/build_console_port.py           # write the files
    python scripts/build_console_port.py --check   # exit 1 if any is stale
"""

