_ATTR_RE = re.compile(r"""([^\s=/>"']+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?""")


class _TreeBuilder(HTMLParser):
    """Template HTML -> nested lists, preserving attribute case and order.

    ``html.parser`` tokenizes without the HTML tree builder's foster-parenting,
    so ``<sc-for>`` inside ``<tbody>`` stays where it was written.
    """

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.root: list[Any] = ["#root", {}, []]
        self.stack: list[list[Any]] = [self.root]

    def _attrs(self) -> dict[str, str]:
        raw = self.get_starttag_text() or ""
        body = raw[raw.index(" ") :] if " " in raw.split(">")[0] else ""
        body = body.rstrip(">").rstrip("/")
        out: dict[str, str] = {}
        for m in _ATTR_RE.finditer(body):
            name = m.group(1)
            value = next((g for g in m.group(2, 3, 4) if g is not None), "")
            out[name] = _unescape(value)
        return out

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        node: list[Any] = [tag, self._attrs(), []]
        self.stack[-1][2].append(node)
        if tag not in VOID:
            self.stack.append(node)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.stack[-1][2].append([tag, self._attrs(), []])

    def handle_endtag(self, tag: str) -> None:
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i][0] == tag:
                del self.stack[i:]
                return

    def handle_data(self, data: str) -> None:
        if not data.strip() and " " not in data:
            return  # the prototype runtime drops whitespace-only text without a space
        self.stack[-1][2].append(data)


def _unescape(value: str) -> str:
    import html

    return html.unescape(value)


def _extract(source: str) -> tuple[str, str, str]:
    """(template markup, helmet CSS, logic source) from the prototype page."""
    xdc = source[source.index("<x-dc>") + len("<x-dc>") : source.index("</x-dc>")]
    helmet = xdc[xdc.index("<helmet>") : xdc.index("</helmet>")]
    template = xdc[xdc.index("</helmet>") + len("</helmet>") :]
    css = helmet[helmet.index("<style>") + len("<style>") : helmet.index("</style>")]
    open_tag = '<script type="text/x-dc" data-dc-script>'
    logic = source[source.index(open_tag) + len(open_tag) :]
    logic = logic[: logic.rindex("</script>")]
    return template, css, logic


def _apply(text: str, patches: tuple[tuple[str, str, str], ...], where: str) -> str:
    for desc, old, new in patches:
        count = text.count(old)
        if count != 1:
            raise SystemExit(f"{where}: patch '{desc}' matched {count} times (expected 1)")
        text = text.replace(old, new)
    return text


def _pseudo(tree: list[Any], rules: list[str]) -> None:
    """``style-hover="css"`` -> class ``scpN`` plus a ``.scpN:hover`` rule."""
    if not isinstance(tree, list):
        return
    attrs: dict[str, str] = tree[1]
    for name in [n for n in attrs if n.startswith("style-")]:
        pseudo = name[len("style-") :]
        css = attrs.pop(name)
        cls = f"scp{len(rules)}"
        sel = f".{cls}::{pseudo}" if pseudo in ("before", "after") else f".{cls}:{pseudo}"
        rules.append(f"{sel}{{{css}}}")
        attrs["class"] = (attrs.get("class", "") + " " + cls).strip()
    for src in [a for a in ("src",) if attrs.get(a) in IMAGES]:
        attrs[src] = "/static/console/" + attrs[src]
    for child in tree[2]:
        _pseudo(child, rules)


def build() -> dict[str, str]:
    """Every generated file's text, keyed by file name under ``static/console``."""
    source = PROTOTYPE.read_text(encoding="utf-8")
    template, helmet_css, logic = _extract(source)
    template = _apply(template, TEMPLATE_PATCHES, "template")
    parser = _TreeBuilder()
    parser.feed(template)
    parser.close()
    rules: list[str] = []
    for child in parser.root[2]:
        _pseudo(child, rules)
    tree = parser.root[2]
    files: dict[str, str] = {}
    files["template.js"] = (
        HEADER_JS.format(src="Mercury CLI.dc.html (template)")
        + "window.MCLI_TEMPLATE = "
        + json.dumps(tree, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    logic = _apply(logic, LOGIC_PATCHES, "logic")
    files["logic.js"] = (
        HEADER_JS.format(src="Mercury CLI.dc.html (logic class)")
        + "window.MCLI_Component = (function (DCLogic, StreamableLogic, React) {\n"
        + "  'use strict';\n"
        + logic.strip("\n")
        + "\n  return Component;\n})(window.DCLogic, window.DCLogic, window.React);\n"
    )
    helmet_css = _apply(helmet_css, HELMET_CSS_PATCHES, "helmet css")
    files["port.css"] = (
        HEADER_CSS.format(src="Mercury CLI.dc.html (helmet style + style-* rules)")
        + helmet_css.strip()
        + "\n"
        + "\n".join(rules)
        + "\n"
    )
    tokens = TOKENS.read_text(encoding="utf-8")
    tokens = "\n".join(line for line in tokens.splitlines() if not line.startswith("@import"))
    files["tokens.css"] = (
        HEADER_CSS.format(src="_ds/.../colors_and_type.css (font @import removed)")
        + tokens.strip()
        + "\n"
    )
    for src_name, out_name in MODULES.items():
        text = (DESIGN / src_name).read_text(encoding="utf-8")
        text = _apply(text, MODULE_PATCHES.get(src_name, ()), src_name)
        files[out_name] = HEADER_JS.format(src=src_name) + text
    return files


def main(argv: list[str] | None = None) -> int:
    """Write the generated files, or with ``--check`` report staleness."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a file is stale")
    args = parser.parse_args(argv)
    files = build()
    stale = []
    for name, text in files.items():
        path = OUT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
            if not args.check:
                path.write_text(text, encoding="utf-8")
    for image in IMAGES:
        src, dst = DESIGN / image, OUT / image
        if not dst.exists() or dst.read_bytes() != src.read_bytes():
            stale.append(image)
            if not args.check:
                shutil.copyfile(src, dst)
    if args.check:
        if stale:
            print("STALE: " + ", ".join(stale) + "; run python scripts/build_console_port.py")
            return 1
        print("console port is current")
        return 0
    print(f"wrote {len(stale)} file(s) to {OUT.relative_to(REPO)}: {', '.join(stale) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
