#!/usr/bin/env python3
# Copyright (C) 2025 Steel Security Advisors LLC
"""Persist benchmark results to ``main`` via a PR using the Git Database API.

Replaces the previous ``git commit && git push origin HEAD:main`` flow
which was rejected by ``main``'s branch protection ruleset
(``Changes must be made through a pull request`` +
``Commits must have verified signatures``).

Signature handling
------------------
This script does **not** supply a detached ``signature`` field in the
``POST /git/commits`` payload.  Rule 4 of the protection ruleset
(*commits must have verified signatures*) is satisfied externally —
GitHub auto-signs commits made via the Git Database API on behalf of
``github-actions[bot]`` with its web-flow signing key, **but only when
the call is authenticated with the workflow's ``GITHUB_TOKEN``** (or a
GitHub App installation token that is allowed to act as the bot).  If
the workflow is reconfigured to consume a Personal Access Token via
``BENCHMARK_BOT_TOKEN``, the resulting commits will land **unverified**
and will fail the ruleset; the alternative is to extend this script to
compute and submit a detached PGP/SSH signature (not implemented).

Strategy
--------
GitHub Git Database API is used to:

    1. Read each file from disk.
    2. POST /repos/{owner}/{repo}/git/blobs           — create blobs.
    3. GET  /repos/{owner}/{repo}/git/ref/heads/main  — get base SHA.
    4. GET  /repos/{owner}/{repo}/git/commits/{sha}   — get base tree.
    5. POST /repos/{owner}/{repo}/git/trees           — new tree from base + blobs.
    6. POST /repos/{owner}/{repo}/git/commits         — create commit
       (signed externally by GitHub's web-flow key when the API call is
       authenticated as ``github-actions[bot]`` via ``GITHUB_TOKEN``;
       unverified otherwise — see "Signature handling" above).
    7. POST /repos/{owner}/{repo}/git/refs            — create the
       feature-branch ref pointing at the new commit, OR
       PATCH /repos/{owner}/{repo}/git/refs/heads/{branch} (force) if
       the branch already exists from a prior run.
    8. POST /repos/{owner}/{repo}/pulls               — open a PR
       from the feature branch into ``base`` (skipped if a PR is
       already open for the same head/base pair; in that case the
       existing PR is updated with the freshly supplied
       ``--pr-title`` and ``--pr-body``).

Caveat
------
GitHub deliberately does NOT trigger downstream workflows from events
caused by the default ``GITHUB_TOKEN``.  The PR opened by this script
will therefore start with all required status checks **pending** and
will need to be unblocked by either:

  - re-running the CI workflow manually on the PR head SHA, or
  - a maintainer pushing an empty commit to the persistence branch.

**Do not** swap ``GITHUB_TOKEN`` for a Personal Access Token to
break the loop-prevention.  As described in "Signature handling"
above, this script does not submit a detached signature, so
PAT-authenticated Git Database commits land ``Unverified`` and fail
rule 4 of the protection ruleset.  The benchmark workflow's
persister steps therefore export
``GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}`` unconditionally.  An
earlier iteration of the workflow used a
``secrets.BENCHMARK_BOT_TOKEN || secrets.GITHUB_TOKEN`` expression
to leave room for a future GitHub App installation token, but the
expression cannot distinguish a PAT from an App token by secret
name; the fallback was removed.  Wiring an installation token in
the future requires a separately named secret (e.g.
``BENCHMARK_BOT_APP_TOKEN``) and is a focused-PR job.

This script does not enable auto-merge — that is intentionally a
maintainer decision.  Run with ``--enable-automerge`` to opt in.

Usage
-----
::

    GITHUB_TOKEN=ghp_xxx     GITHUB_REPOSITORY=owner/repo         python scripts/persist_benchmark_to_pr.py             --base main             --branch ci/benchmark-results             --commit-message "ci(benchmark): persist run AUC=0.84 F1=0.63"             --pr-title "ci(benchmark): auto-update Latest Benchmark Results"             --pr-body "Generated by .github/workflows/benchmark.yml"             --files benchmarks/mercury_benchmark_results.json README.md

Exit codes:
    0  - PR opened or updated (or a no-op because nothing changed).
    1  - hard failure (auth missing, API rejected the call, file
         missing in CI workspace, etc.).
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any

GITHUB_API = "https://api.github.com"
USER_AGENT = "mercury-agent-benchmark-bot"


def _api(method: str, path: str, token: str, payload: dict[str, Any] | None = None) -> Any:
    """Issue a GitHub REST API call and return parsed JSON (or {} on 204)."""
    url = f"{GITHUB_API}{path}"
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": USER_AGENT,
    }
    if data is not None:
        headers["Content-Type"] = "application/json"

    req = urllib.request.Request(url, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req) as resp:
            body = resp.read()
            if not body:
                return {}
            return json.loads(body)
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(
            f"GitHub API {method} {path} failed: HTTP {exc.code} — {detail}"
        ) from exc


def get_branch_sha(owner: str, repo: str, branch: str, token: str) -> str:
    ref = _api("GET", f"/repos/{owner}/{repo}/git/ref/heads/{branch}", token)
    return str(ref["object"]["sha"])


def get_commit_tree_sha(owner: str, repo: str, commit_sha: str, token: str) -> str:
    commit = _api("GET", f"/repos/{owner}/{repo}/git/commits/{commit_sha}", token)
    return str(commit["tree"]["sha"])


def create_blob(owner: str, repo: str, content: bytes, token: str) -> str:
    encoded = base64.b64encode(content).decode("ascii")
    response = _api(
        "POST",
        f"/repos/{owner}/{repo}/git/blobs",
        token,
        payload={"content": encoded, "encoding": "base64"},
    )
    return str(response["sha"])


def create_tree(
    owner: str,
    repo: str,
    base_tree_sha: str,
    blob_entries: list[tuple[str, str]],
    token: str,
) -> str:
    tree_payload = [
        {"path": path, "mode": "100644", "type": "blob", "sha": blob_sha}
        for path, blob_sha in blob_entries
    ]
    response = _api(
        "POST",
        f"/repos/{owner}/{repo}/git/trees",
        token,
        payload={"base_tree": base_tree_sha, "tree": tree_payload},
    )
    return str(response["sha"])


def create_commit(
    owner: str,
    repo: str,
    message: str,
    tree_sha: str,
    parent_sha: str,
    token: str,
) -> str:
    response = _api(
        "POST",
        f"/repos/{owner}/{repo}/git/commits",
        token,
        payload={"message": message, "tree": tree_sha, "parents": [parent_sha]},
    )
    return str(response["sha"])


def upsert_branch_ref(owner: str, repo: str, branch: str, commit_sha: str, token: str) -> None:
    """Create branch ref, or fast-forward / force-update it if it already exists.

    The fallback to PATCH is intentionally narrow: GitHub returns
    HTTP 422 for several distinct validation failures (invalid ref name,
    bad SHA, ref already exists, etc.).  Treating every 422 as
    "branch already exists" would mask the real failure by retrying a
    PATCH against a ref that was never created.  We therefore require
    the response body to specifically contain ``Reference already exists``
    before falling through; any other ``RuntimeError`` is re-raised
    unchanged so callers see the original create-ref error.
    """
    try:
        _api(
            "POST",
            f"/repos/{owner}/{repo}/git/refs",
            token,
            payload={"ref": f"refs/heads/{branch}", "sha": commit_sha},
        )
        print(f"  Created branch ref refs/heads/{branch}")
        return
    except RuntimeError as exc:
        if "Reference already exists" not in str(exc):
            raise

    # Branch exists; force-update it to the new commit.
    _api(
        "PATCH",
        f"/repos/{owner}/{repo}/git/refs/heads/{branch}",
        token,
        payload={"sha": commit_sha, "force": True},
    )
    print(f"  Force-updated existing branch ref refs/heads/{branch}")


def find_open_pr(owner: str, repo: str, head_branch: str, base: str, token: str) -> int | None:
    head = f"{owner}:{head_branch}"
    encoded_head = urllib.parse.quote(head, safe=":")
    response = _api(
        "GET",
        f"/repos/{owner}/{repo}/pulls?state=open&base={base}&head={encoded_head}",
        token,
    )
    if isinstance(response, list) and response:
        return int(response[0]["number"])
    return None


def create_pull_request(
    owner: str,
    repo: str,
    title: str,
    body: str,
    head: str,
    base: str,
    token: str,
) -> int:
    response = _api(
        "POST",
        f"/repos/{owner}/{repo}/pulls",
        token,
        payload={"title": title, "body": body, "head": head, "base": base},
    )
    return int(response["number"])


def update_pull_request(
    owner: str,
    repo: str,
    pr_number: int,
    title: str,
    body: str,
    token: str,
) -> None:
    """PATCH the title and body of an existing open PR.

    Used when a benchmark rerun produces a fresh AUC/F1 but the
    persistence branch already has an open PR — without this, the
    PR header would keep the metrics from the first run while the
    underlying tree advances.
    """
    _api(
        "PATCH",
        f"/repos/{owner}/{repo}/pulls/{pr_number}",
        token,
        payload={"title": title, "body": body},
    )


def enable_automerge(owner: str, repo: str, pr_number: int, merge_method: str, token: str) -> None:
    """Enable PR auto-merge via the GraphQL API (REST has no auto-merge endpoint)."""
    pr = _api("GET", f"/repos/{owner}/{repo}/pulls/{pr_number}", token)
    pr_node_id = pr["node_id"]

    query = """
    mutation EnableAutoMerge($pr: ID!, $method: PullRequestMergeMethod!) {
      enablePullRequestAutoMerge(input: {pullRequestId: $pr, mergeMethod: $method}) {
        pullRequest { number autoMergeRequest { enabledAt } }
      }
    }
    """
    payload = {
        "query": query,
        "variables": {"pr": pr_node_id, "method": merge_method.upper()},
    }
    url = f"{GITHUB_API}/graphql"
    headers = {
        "Authorization": f"Bearer {token}",
        "User-Agent": USER_AGENT,
        "Accept": "application/json",
        "Content-Type": "application/json",
    }
    req = urllib.request.Request(
        url, data=json.dumps(payload).encode("utf-8"), method="POST", headers=headers
    )
    try:
        with urllib.request.urlopen(req) as resp:
            body = json.loads(resp.read())
        if "errors" in body:
            print(f"  Auto-merge enable failed: {body['errors']}", file=sys.stderr)
        else:
            print(f"  Auto-merge enabled on PR #{pr_number}")
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        print(
            f"  Auto-merge enable HTTP {exc.code}: {detail}",
            file=sys.stderr,
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", default="main", help="Base branch (default: main)")
    parser.add_argument("--branch", required=True, help="Feature branch to create / update")
    parser.add_argument("--commit-message", required=True)
    parser.add_argument("--pr-title", required=True)
    parser.add_argument("--pr-body", default="")
    parser.add_argument(
        "--files",
        nargs="+",
        required=True,
        help="Repo-relative paths to commit (missing files are skipped with a warning)",
    )
    parser.add_argument(
        "--no-pr-metadata-update",
        action="store_true",
        help=(
            "If the open PR already exists, do NOT PATCH its title/body "
            "to the values supplied here.  Use on follow-up persistence "
            "steps in the same workflow run that should append commits "
            "to the existing PR without overwriting the metric-rich "
            "title/body the earlier step set."
        ),
    )
    parser.add_argument(
        "--enable-automerge",
        action="store_true",
        help="Enable PR auto-merge (squash) — only takes effect once required checks pass",
    )
    parser.add_argument(
        "--merge-method",
        default="squash",
        choices=["merge", "squash", "rebase"],
        help="Merge method for --enable-automerge",
    )
    args = parser.parse_args()

    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        print("ERROR: GITHUB_TOKEN env var not set", file=sys.stderr)
        return 1

    repo_full = os.environ.get("GITHUB_REPOSITORY", "")
    if "/" not in repo_full:
        print(
            f"ERROR: GITHUB_REPOSITORY env var not set or malformed: {repo_full!r}",
            file=sys.stderr,
        )
        return 1
    owner, repo = repo_full.split("/", 1)

    files_to_commit: list[tuple[str, bytes]] = []
    for path_str in args.files:
        # Validate that the path is a safe repo-relative path suitable
        # for use as a Git tree entry.  The GitHub Git Database API
        # rejects absolute paths and paths with traversal segments;
        # catching these early produces a clear error rather than a
        # cryptic 422 from the API.
        normalized = Path(path_str)
        if normalized.is_absolute():
            print(
                f"ERROR: --files path must be repo-relative, got absolute: {path_str}",
                file=sys.stderr,
            )
            return 1
        if ".." in normalized.parts:
            print(
                f"ERROR: --files path must not contain '..' segments: {path_str}",
                file=sys.stderr,
            )
            return 1
        if not normalized.exists():
            print(f"WARNING: skipping non-existent file: {path_str}")
            continue
        files_to_commit.append((path_str, normalized.read_bytes()))

    if not files_to_commit:
        print("No files to commit; nothing to do.")
        return 0

    print(f"Persisting {len(files_to_commit)} file(s) to {owner}/{repo} via PR...")

    base_sha = get_branch_sha(owner, repo, args.base, token)
    print(f"  {args.base} HEAD: {base_sha}")
    base_tree_sha = get_commit_tree_sha(owner, repo, base_sha, token)

    # Detect no-op: if every file's current content already matches the
    # version on `base`, there is nothing to commit.  This avoids opening
    # empty PRs when re-running the workflow with no changes.
    blob_entries: list[tuple[str, str]] = []
    for path, content in files_to_commit:
        blob_sha = create_blob(owner, repo, content, token)
        print(f"  blob {path}: {blob_sha[:8]}")
        blob_entries.append((path, blob_sha))

    tree_sha = create_tree(owner, repo, base_tree_sha, blob_entries, token)
    print(f"  tree: {tree_sha[:8]}")

    if tree_sha == base_tree_sha:
        print("  tree identical to base; nothing to commit.")
        return 0

    # If the persistence branch already exists and its head commit's
    # tree matches what we would create, skip the commit + force-push.
    # Without this, every no-change rerun would force-update the
    # branch ref to a fresh commit SHA with identical content, which
    # resets required-check approvals on the bot PR.  The PR metadata
    # PATCH below still runs so a maintainer-visible rerun is recorded
    # in the PR title/body.
    # Narrow the except: only treat HTTP 404 (branch genuinely doesn't
    # exist) as "skip the no-op check".  A transient 403 / 500 /
    # rate-limit / network error must NOT be swallowed here — if we
    # silently fell through to commit + force-push under those
    # conditions, we'd churn an open bot PR's required-check approvals
    # on every transient API failure, defeating the whole point of
    # this safeguard.  Re-raise anything else so the operator sees
    # the real failure and the workflow fails loudly.
    try:
        existing_branch_head: str | None = get_branch_sha(owner, repo, args.branch, token)
    except RuntimeError as exc:
        if "HTTP 404" not in str(exc):
            raise
        existing_branch_head = None

    if existing_branch_head is not None:
        existing_tree_sha = get_commit_tree_sha(owner, repo, existing_branch_head, token)
        if existing_tree_sha == tree_sha:
            print(
                f"  tree identical to existing {args.branch} HEAD "
                f"({existing_branch_head[:8]}); skipping commit + branch update "
                "to preserve required-check approvals on the bot PR."
            )
            existing_pr = find_open_pr(owner, repo, args.branch, args.base, token)
            if existing_pr is not None:
                # Existing PR for the same head/base: refresh title/body
                # (unless explicitly opted out) and honour --enable-automerge.
                # Skipping the auto-merge call here would mean a rerun of
                # the workflow with --enable-automerge passed cannot turn
                # auto-merge ON for an already-open PR, which is exactly
                # the maintainer-facing operation the flag is meant to do.
                if not args.no_pr_metadata_update:
                    update_pull_request(
                        owner, repo, existing_pr, args.pr_title, args.pr_body, token
                    )
                    print(f"  refreshed PR #{existing_pr} title/body only.")
                else:
                    print(
                        f"  PR #{existing_pr} title/body left untouched "
                        "(--no-pr-metadata-update)."
                    )
                if args.enable_automerge:
                    enable_automerge(owner, repo, existing_pr, args.merge_method, token)
                return 0
            else:
                # Branch already has the desired tree but there's no open
                # PR — most likely a previously open PR was closed without
                # deleting the branch.  Without this fall-through, the
                # latest benchmark artefacts would be stranded on
                # ``ci/benchmark-results`` with no path back to ``main``,
                # and subsequent identical reruns would keep returning
                # here without ever publishing the update.  Open a fresh
                # PR with the same head SHA so the loop is unblocked.
                print(
                    f"  no open PR for head {args.branch} -> {args.base}; "
                    "opening a fresh PR against the existing branch head."
                )
                pr_number = create_pull_request(
                    owner,
                    repo,
                    args.pr_title,
                    args.pr_body,
                    args.branch,
                    args.base,
                    token,
                )
                print(f"  opened PR #{pr_number}")
                if args.enable_automerge:
                    enable_automerge(owner, repo, pr_number, args.merge_method, token)
                return 0

    commit_sha = create_commit(owner, repo, args.commit_message, tree_sha, base_sha, token)
    print(
        f"  commit: {commit_sha[:8]} "
        "(GitHub-signed when authenticated as github-actions[bot]; see module docstring)"
    )

    upsert_branch_ref(owner, repo, args.branch, commit_sha, token)

    existing = find_open_pr(owner, repo, args.branch, args.base, token)
    if existing is not None:
        # The benchmark workflow encodes the current AUC / F1 / commit SHA
        # into ``--pr-title`` and ``--pr-body``.  If we silently reuse the
        # existing PR without refreshing those fields, every rerun will
        # keep displaying the *first* run's metrics in the PR header
        # while the underlying tree advances.  PATCH the title/body now
        # so reviewers see numbers that match the latest commit — UNLESS
        # ``--no-pr-metadata-update`` is set, which lets follow-up
        # persistence steps in the same workflow run append commits
        # without overwriting the metric-rich title set by an earlier
        # step.
        if not args.no_pr_metadata_update:
            update_pull_request(owner, repo, existing, args.pr_title, args.pr_body, token)
            print(f"  reused existing open PR #{existing}; refreshed title and body")
        else:
            print(
                f"  reused existing open PR #{existing}; title/body left untouched "
                "(--no-pr-metadata-update)."
            )
        pr_number = existing
    else:
        pr_number = create_pull_request(
            owner,
            repo,
            args.pr_title,
            args.pr_body,
            args.branch,
            args.base,
            token,
        )
        print(f"  opened PR #{pr_number}")

    if args.enable_automerge:
        enable_automerge(owner, repo, pr_number, args.merge_method, token)

    return 0


if __name__ == "__main__":
    sys.exit(main())
