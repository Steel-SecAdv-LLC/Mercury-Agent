"""Measure — and *enforce* — the Mercury Agent codebase-scale numbers.

This script is the single source of truth for the structural counts that
the README advertises.  It reports, all measured from what is actually on
disk (never hand-typed):

  * source files and SLOC under ``src/omni_mercury_engine``,
  * top-level *Python packages* (a directory is only counted if it holds an
    ``__init__.py`` — this excludes ``__pycache__``, ``*.egg-info`` and any
    hidden directory, which the previous implementation wrongly counted),
  * detector classes (``class *Detector``) under ``detectors/``,
  * data-loader classes (``class *Loader``) under ``loaders/``,
  * test files and test SLOC,
  * ``import torch`` / ``from torch`` modules and ``class …(nn.Module)``
    definitions,
  * GitHub Actions workflow files.

It has no third-party dependencies, so it runs in any CI environment
without installing the Mercury Agent package.

Modes
-----
    python scripts/measure_codebase_scale.py            # human table
    python scripts/measure_codebase_scale.py --json     # machine JSON
    python scripts/measure_codebase_scale.py --check README.md
        # exit 0 if the README scale block matches the measured numbers,
        # exit 1 (printing a diff) if it has drifted.  This is the CI gate
        # that makes doc/code divergence impossible to merge.
    python scripts/measure_codebase_scale.py --update README.md
        # rewrite the README scale block in place from the measured numbers.

The README block is delimited by the ``<!-- SCALE:START -->`` and
``<!-- SCALE:END -->`` HTML comments so the rendered numbers stay
deterministic and machine-regenerable.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import TypedDict

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "omni_mercury_engine"
TESTS = ROOT / "tests"
DETECTORS = SRC / "detectors"
LOADERS = SRC / "loaders"
WORKFLOWS = ROOT / ".github" / "workflows"

TORCH_IMPORT_RE = re.compile(r"^\s*(?:from\s+torch\b|import\s+torch\b)", re.MULTILINE)
NN_MODULE_RE = re.compile(r"^\s*class\s+\w+\([^)]*\bnn\.Module\b[^)]*\):", re.MULTILINE)
DETECTOR_CLASS_RE = re.compile(r"^class\s+\w*Detector\b", re.MULTILINE)
#: A detector a caller can use: not an abstract ``Base*`` class, a ``_private`` helper,
#: or the bare ``Detector`` typing protocol.
PUBLIC_DETECTOR_CLASS_RE = re.compile(r"^class\s+(?!_|Base[A-Z])\w+Detector\b", re.MULTILINE)
LOADER_CLASS_RE = re.compile(r"^class\s+\w*Loader\b", re.MULTILINE)

# LOC figures are advertised as approximate (the ``~`` prefix) order-of-
# magnitude scale, not exact line tallies.  Rounding them to the nearest
# ``LOC_BUCKET`` keeps the CI drift gate stable under routine churn — adding a
# few lines to one test must not force a README regeneration — while still
# surfacing real structural growth.  Discrete counts (files, packages, classes,
# workflows) are exact and never bucketed; those are the signal the original
# rewrite was protecting (e.g. the 512→603 source-file drift).
LOC_BUCKET = 1000

# Rounding alone cannot make the drift gate churn-stable: at an LOC count
# sitting just below a half-bucket boundary, a handful of added lines flips
# the nearest-bucket figure and demands a README rewrite for noise.  The
# stateful surfaces (``--check`` / ``--update``) therefore apply hysteresis:
# a stored, bucket-aligned figure stays accepted while it is within
# ``LOC_STALENESS_LIMIT`` of the actual count.  A stored figure can be stale
# by at most one bucket before the gate fires — consistent with the ``~``
# order-of-magnitude contract — and small churn can never oscillate the
# README, at any starting LOC.  Pure rendering (``render_block`` without
# stored figures) is unchanged and exact-to-the-bucket.
LOC_STALENESS_LIMIT = LOC_BUCKET

SCALE_START = "<!-- SCALE:START -->"
SCALE_END = "<!-- SCALE:END -->"
# Stamped into the generated block so readers know how to regenerate it.
SCALE_PROVENANCE = (
    "_Generated by `python scripts/measure_codebase_scale.py --update README.md` "
    "and gated in CI (`scripts/measure_codebase_scale.py --check README.md`); "
    "do not hand-edit between the markers._"
)


class ScaleStats(TypedDict):
    """Measured codebase-scale numbers, keyed exactly as emitted by ``--json``."""

    src_files: int
    src_loc: int
    subpackages: list[str]
    subpackage_count: int
    detector_classes: int
    public_detector_classes: int
    detector_subpackages: int
    loader_classes: int
    test_files: int
    test_loc: int
    torch_importing_files: int
    nn_module_subclasses: int
    workflow_count: int


def _round_loc(loc: int) -> int:
    """Bucket an LOC count to the nearest ``LOC_BUCKET`` for stable display.

    The README advertises LOC with a ``~`` prefix; bucketing makes the drift
    gate insensitive to small, routine line churn while still tracking real
    growth (any net change of at least half a bucket moves the figure).
    """
    return int(round(loc / LOC_BUCKET) * LOC_BUCKET)


def _count_lines(paths: list[Path]) -> int:
    total = 0
    for p in paths:
        try:
            with p.open("r", encoding="utf-8", errors="replace") as fh:
                for _ in fh:
                    total += 1
        except OSError:
            continue
    return total


def _is_package_dir(path: Path) -> bool:
    """A directory counts as a subpackage only if it is a real Python package.

    Excludes ``__pycache__``, hidden directories (``.foo``) and build
    artifacts such as ``*.egg-info`` — none of which are importable
    subpackages, even though the old ``p.is_dir()`` check counted them.
    """
    if not path.is_dir():
        return False
    name = path.name
    if name.startswith(".") or name == "__pycache__" or name.endswith(".egg-info"):
        return False
    return (path / "__init__.py").exists()


def _count_class_matches(directory: Path, pattern: re.Pattern[str]) -> int:
    if not directory.is_dir():
        return 0
    total = 0
    for p in sorted(directory.rglob("*.py")):
        try:
            total += len(pattern.findall(p.read_text(encoding="utf-8", errors="replace")))
        except OSError:
            continue
    return total


def measure() -> ScaleStats:
    src_files = sorted(SRC.rglob("*.py")) if SRC.is_dir() else []
    test_files = sorted(TESTS.rglob("test_*.py")) if TESTS.is_dir() else []
    subpackages = (
        sorted(p.name for p in SRC.iterdir() if _is_package_dir(p)) if SRC.is_dir() else []
    )
    workflows = sorted(p.name for p in WORKFLOWS.glob("*.yml")) if WORKFLOWS.is_dir() else []

    torch_files = 0
    nn_module_classes = 0
    for p in src_files:
        try:
            text = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if TORCH_IMPORT_RE.search(text):
            torch_files += 1
        nn_module_classes += len(NN_MODULE_RE.findall(text))

    return {
        "src_files": len(src_files),
        "src_loc": _count_lines(src_files),
        "subpackages": subpackages,
        "subpackage_count": len(subpackages),
        "detector_classes": _count_class_matches(DETECTORS, DETECTOR_CLASS_RE),
        "public_detector_classes": _count_class_matches(SRC, PUBLIC_DETECTOR_CLASS_RE),
        "detector_subpackages": sum(
            1 for pkg in subpackages if _count_class_matches(SRC / pkg, PUBLIC_DETECTOR_CLASS_RE)
        ),
        "loader_classes": _count_class_matches(LOADERS, LOADER_CLASS_RE),
        "test_files": len(test_files),
        "test_loc": _count_lines(test_files),
        "torch_importing_files": torch_files,
        "nn_module_subclasses": nn_module_classes,
        "workflow_count": len(workflows),
    }


def render_block(
    stats: ScaleStats,
    *,
    src_loc_figure: int | None = None,
    test_loc_figure: int | None = None,
) -> str:
    """Render the deterministic README scale block (between the markers).

    ``src_loc_figure`` / ``test_loc_figure`` override the freshly rounded LOC
    figures with already-published ones — the hysteresis path ``--check`` and
    ``--update`` use to stay stable under small churn (see
    :data:`LOC_STALENESS_LIMIT`).  Omitted, the block is rendered from the
    measured counts, rounded to the nearest :data:`LOC_BUCKET`.
    """
    src_loc = _round_loc(int(stats["src_loc"])) if src_loc_figure is None else src_loc_figure
    test_loc = _round_loc(int(stats["test_loc"])) if test_loc_figure is None else test_loc_figure
    rows = [
        ("Python source files in `src/omni_mercury_engine/`", f"**{stats['src_files']}**"),
        ("Source lines of code (LOC)", f"**~{src_loc:,}**"),
        (
            "Top-level subpackages (true Python packages with `__init__.py`)",
            f"**{stats['subpackage_count']}**",
        ),
        (
            "Files importing PyTorch (optional `[ml]` extra)",
            f"**{stats['torch_importing_files']}**",
        ),
        ("Distinct `torch.nn.Module` subclasses", f"**{stats['nn_module_subclasses']}**"),
        (
            "Detector classes (`class *Detector`) in `detectors/`",
            f"**{stats['detector_classes']}**",
        ),
        (
            "Public detector classes package-wide (`class *Detector`, not `Base*` or `_private`)",
            f"**{stats['public_detector_classes']} in {stats['detector_subpackages']} subpackages**",
        ),
        ("Data-loader classes (`class *Loader`) in `loaders/`", f"**{stats['loader_classes']}**"),
        (
            "Test modules (`test_*.py`) / total test LOC",
            f"**{stats['test_files']} modules / ~{test_loc:,} LOC**",
        ),
        ("GitHub Actions workflows", f"**{stats['workflow_count']}**"),
    ]
    lines = [SCALE_START, "", "| Measurement | Value |", "|---|---|"]
    lines += [f"| {label} | {value} |" for label, value in rows]
    lines += ["", SCALE_PROVENANCE, "", SCALE_END]
    return "\n".join(lines)


_LOC_FIGURE_RE = re.compile(r"~(\d{1,3}(?:,\d{3})*|\d+)")


def _stored_loc_figures(block: str) -> tuple[int, int] | None:
    """The (src, test) bucketed LOC figures published in a rendered block.

    ``None`` when the block does not carry exactly the two ``~``-prefixed
    figures ``render_block`` emits (hand-edited or structurally stale blocks
    fall back to the exact comparison and are reported as drift).
    """
    figures = [int(m.replace(",", "")) for m in _LOC_FIGURE_RE.findall(block)]
    if len(figures) != 2:
        return None
    return figures[0], figures[1]


def _loc_figure_fresh(stored: int, actual: int) -> bool:
    """True while a published, bucket-aligned figure is still truthful.

    Freshness means the figure is a multiple of :data:`LOC_BUCKET` (so a
    hand-typed exact count never passes) and within
    :data:`LOC_STALENESS_LIMIT` of the actual measured count.
    """
    return stored % LOC_BUCKET == 0 and abs(actual - stored) <= LOC_STALENESS_LIMIT


def _accepted_loc_figures(block: str, stats: ScaleStats) -> tuple[int | None, int | None]:
    """Published LOC figures to keep, per the hysteresis contract.

    Returns ``(src_figure, test_figure)`` where each entry is the stored
    figure when it is still fresh against the measured count, else ``None``
    (meaning: re-round from the measurement).
    """
    stored = _stored_loc_figures(block)
    if stored is None:
        return None, None
    src_fig = stored[0] if _loc_figure_fresh(stored[0], int(stats["src_loc"])) else None
    test_fig = stored[1] if _loc_figure_fresh(stored[1], int(stats["test_loc"])) else None
    return src_fig, test_fig


def _splice(readme_text: str, new_block: str) -> str:
    start = readme_text.index(SCALE_START)
    end = readme_text.index(SCALE_END) + len(SCALE_END)
    return readme_text[:start] + new_block + readme_text[end:]


def _extract_block(readme_text: str) -> str:
    start = readme_text.index(SCALE_START)
    end = readme_text.index(SCALE_END) + len(SCALE_END)
    return readme_text[start:end]


#: A prose claim of a detector-class count anywhere in the README.
DETECTOR_CLAIM_RE = re.compile(r"\b(\d+) (detector classes)\b", re.IGNORECASE)


def _stale_detector_claims(text: str, count: int) -> list[str]:
    """README prose citing a detector-class count other than the measured one."""
    outside = text.split(SCALE_START, 1)[0] + text.rsplit(SCALE_END, 1)[-1]
    return [m.group(0) for m in DETECTOR_CLAIM_RE.finditer(outside) if int(m.group(1)) != count]


def _fix_detector_claims(text: str, count: int) -> str:
    head, rest = text.split(SCALE_START, 1)
    block, tail = rest.split(SCALE_END, 1)

    def fix(part: str) -> str:
        return DETECTOR_CLAIM_RE.sub(lambda m: f"{count} {m.group(2)}", part)

    return fix(head) + SCALE_START + block + SCALE_END + fix(tail)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="Emit JSON instead of a table.")
    parser.add_argument(
        "--check",
        metavar="README",
        help="Verify the README scale block matches measured numbers (CI gate).",
    )
    parser.add_argument(
        "--update", metavar="README", help="Rewrite the README scale block in place."
    )
    args = parser.parse_args(argv)

    stats = measure()

    if args.check or args.update:
        readme_path = Path(args.check or args.update)
        try:
            text = readme_path.read_text(encoding="utf-8")
        except OSError as exc:
            print(f"ERROR: cannot read {readme_path}: {exc}", file=sys.stderr)
            return 2
        if SCALE_START not in text or SCALE_END not in text:
            print(
                f"ERROR: {readme_path} is missing the {SCALE_START} / {SCALE_END} markers.",
                file=sys.stderr,
            )
            return 2
        # Hysteresis: keep published LOC figures that are still within one
        # bucket of the measured counts, so small churn never flips the
        # block — even when the measured LOC sits at a rounding boundary.
        current = _extract_block(text)
        src_fig, test_fig = _accepted_loc_figures(current, stats)
        expected = render_block(stats, src_loc_figure=src_fig, test_loc_figure=test_fig)
        public_detectors = int(stats["public_detector_classes"])
        if args.update:
            updated = _fix_detector_claims(_splice(text, expected), public_detectors)
            readme_path.write_text(updated, encoding="utf-8")
            print(f"Updated scale block in {readme_path}.")
            return 0
        stale = _stale_detector_claims(text, public_detectors)
        if stale:
            print(
                f"DRIFT: {readme_path} cites detector-class counts other than the measured "
                f"{public_detectors}: {stale}. Run "
                "`python scripts/measure_codebase_scale.py --update README.md`.",
                file=sys.stderr,
            )
            return 1
        if current.strip() == expected.strip():
            print(f"OK: {readme_path} scale block is up to date.")
            return 0
        print(
            f"DRIFT: {readme_path} scale block is stale. "
            "Run `python scripts/measure_codebase_scale.py --update README.md`.\n"
            "--- measured (expected) ---\n"
            f"{expected}\n"
            "--- README (current) ---\n"
            f"{current}",
            file=sys.stderr,
        )
        return 1

    if args.json:
        json.dump(stats, sys.stdout, indent=2, sort_keys=True)
        sys.stdout.write("\n")
        return 0

    print("Mercury Agent — measured codebase scale")
    print("---------------------------------------")
    print(f"src files:                {stats['src_files']}")
    print(f"src LOC:                  {int(stats['src_loc']):,}")
    print(f"subpackages:              {stats['subpackage_count']}")
    print(f"detector classes:         {stats['detector_classes']}")
    print(
        f"public detector classes:  {stats['public_detector_classes']} in {stats['detector_subpackages']} subpackages"
    )
    print(f"loader classes:           {stats['loader_classes']}")
    print(f"test files:               {stats['test_files']}")
    print(f"test LOC:                 {int(stats['test_loc']):,}")
    print(f"torch-importing files:    {stats['torch_importing_files']}")
    print(f"nn.Module subclasses:     {stats['nn_module_subclasses']}")
    print(f"workflows:                {stats['workflow_count']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
