"""Offline benchmark-integrity gate (ROADMAP row 17 fallback).

The headline "66/75 datasets, Mean ROC-AUC 0.8251" claim lives in three
places that can silently drift apart:

* ``benchmarks/mercury_benchmark_results.json`` -- the committed run
  (``summary`` block + 75 ``per_dataset`` records), regenerated by the
  network-dependent ``benchmark.yml`` pipeline;
* the ``<!-- BENCHMARK:START -->`` … ``<!-- BENCHMARK:END -->`` block in
  ``README.md``, regenerated from that JSON by
  ``scripts/update_readme_benchmarks.py``;
* the per-dataset AUC/F1 numbers a reader trusts.

Row 17 (headline benchmark refresh) is an *external blocker*: a fuller
refresh of the 9 failed, network-dependent corpora needs the full
pipeline with live data. This gate is the **offline CI-gated fallback**
for it -- pure stdlib, no network, no ML deps -- so that while the live
refresh is deferred the committed headline still cannot rot or be
fabricated:

1. **Structural invariants** of the ``summary`` block against the raw
   ``per_dataset`` records: ``total == successful + failed``,
   ``successful == #(records with no error)``,
   ``failed == #(records with a non-empty error)``, and
   ``n_genuine_labeled == #(successful ground_truth-labelled records)``.
2. **Headline recomputation, not restatement**: the mean/median
   ``ensemble_auc`` and ``oracle_f1`` over the genuine-labelled
   (``label_source == "ground_truth"``) successful datasets are
   recomputed from ``per_dataset`` and must equal the ``summary``
   figures. A fabricated headline that does not follow from the
   per-dataset rows fails here.
3. **README parity**: the numbers rendered in the README benchmark
   block (Mean/Median ROC-AUC, Mean Oracle F1, successful/total,
   run timestamp, commit) must match the JSON they were generated from.

The gate fails closed: a missing file, a malformed block, or any
mismatch exits non-zero with a specific diagnostic. It runs as a
blocking step in the ``workflow-hardening`` CI job alongside the other
docs-drift gates (codebase-scale, Lyapunov λ). Regenerate the README
block (``python scripts/update_readme_benchmarks.py``) or re-run the
benchmark pipeline to fix a real drift; do not loosen the gate to make
it pass.

Pure stdlib and import-free of :mod:`omni_mercury_engine`, so it needs
no ML/native install to run.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import statistics
import sys
from pathlib import Path
from typing import Any

#: Datasets whose ``label_source`` counts toward the headline AUC/F1.
#: The ``summary.headline_label_policy`` string documents this policy
#: ("genuine_labels_only (ground_truth | expert_annotated)"); the
#: committed run only exercises ``ground_truth``, and manufactured
#: (``statistical``) labels are excluded as circular.
_GENUINE_LABEL_SOURCES = frozenset({"ground_truth", "expert_annotated"})

#: Relative tolerance for float recomputation equality. The recompute
#: replays the same stdlib ``statistics.mean``/``median`` over the same
#: floats, so equality is exact to well within this bound; the tolerance
#: only absorbs JSON float round-tripping.
_RECOMPUTE_REL_TOL = 1e-9

_START_MARKER = "<!-- BENCHMARK:START -->"
_END_MARKER = "<!-- BENCHMARK:END -->"


class IntegrityError(Exception):
    """A benchmark-integrity invariant was violated."""


def _load_results(path: Path) -> dict[str, Any]:
    """Load and minimally shape-check the benchmark results JSON."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise IntegrityError(f"results file not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise IntegrityError(f"results file is not valid JSON: {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise IntegrityError(f"results root must be a JSON object, got {type(data).__name__}")
    for key in ("summary", "per_dataset", "metadata"):
        if key not in data:
            raise IntegrityError(f"results file missing required top-level key {key!r}")
    if not isinstance(data["per_dataset"], list) or not data["per_dataset"]:
        raise IntegrityError("'per_dataset' must be a non-empty list")
    return data


def _has_error(record: dict[str, Any]) -> bool:
    """True when a per-dataset record represents a failed run."""
    err = record.get("error")
    return err not in (None, "", False)


def _check_structural(summary: dict[str, Any], per_dataset: list[dict[str, Any]]) -> list[str]:
    """Cross-check the summary counts against the raw per-dataset records."""
    errors: list[str] = []
    total = summary.get("total_datasets")
    successful = summary.get("successful")
    failed = summary.get("failed")
    n_genuine = summary.get("n_genuine_labeled")

    obs_total = len(per_dataset)
    obs_failed = sum(1 for r in per_dataset if _has_error(r))
    obs_successful = obs_total - obs_failed
    obs_genuine = sum(
        1
        for r in per_dataset
        if not _has_error(r) and r.get("label_source") in _GENUINE_LABEL_SOURCES
    )

    if total != obs_total:
        errors.append(f"summary.total_datasets={total} but per_dataset has {obs_total} records")
    if successful != obs_successful:
        errors.append(f"summary.successful={successful} but {obs_successful} records have no error")
    if failed != obs_failed:
        errors.append(f"summary.failed={failed} but {obs_failed} records carry an error")
    if isinstance(total, int) and isinstance(successful, int) and isinstance(failed, int):
        if total != successful + failed:
            errors.append(
                f"summary counts inconsistent: total={total} != successful={successful} "
                f"+ failed={failed}"
            )
    if n_genuine != obs_genuine:
        errors.append(
            f"summary.n_genuine_labeled={n_genuine} but {obs_genuine} successful records are "
            f"genuinely labelled ({sorted(_GENUINE_LABEL_SOURCES)})"
        )
    return errors


def _recompute(per_dataset: list[dict[str, Any]], field: str) -> tuple[float, float] | None:
    """Mean/median of *field* over successful, genuinely-labelled datasets."""
    values = [
        r[field]
        for r in per_dataset
        if not _has_error(r)
        and r.get("label_source") in _GENUINE_LABEL_SOURCES
        and isinstance(r.get(field), (int, float))
    ]
    if not values:
        return None
    return statistics.mean(values), statistics.median(values)


def _check_recomputed_headline(
    summary: dict[str, Any], per_dataset: list[dict[str, Any]]
) -> list[str]:
    """Recompute the headline AUC/F1 from per_dataset and match the summary."""
    errors: list[str] = []
    checks = (
        ("ensemble_auc", "mean_auc", "median_auc"),
        ("oracle_f1", "mean_oracle_f1", "median_oracle_f1"),
    )
    for field, mean_key, median_key in checks:
        recomputed = _recompute(per_dataset, field)
        if recomputed is None:
            errors.append(f"no genuinely-labelled datasets carry {field!r}; cannot verify headline")
            continue
        obs_mean, obs_median = recomputed
        for label, obs, claimed in (
            (mean_key, obs_mean, summary.get(mean_key)),
            (median_key, obs_median, summary.get(median_key)),
        ):
            if not isinstance(claimed, (int, float)):
                errors.append(f"summary.{label} missing or non-numeric ({claimed!r})")
            elif not math.isclose(obs, float(claimed), rel_tol=_RECOMPUTE_REL_TOL):
                errors.append(
                    f"summary.{label}={claimed} but recomputed from per_dataset[{field}] "
                    f"is {obs!r}"
                )
    return errors


def _readme_current_value(block: str, metric: str) -> str | None:
    """Extract the 'Current' column of a metric row in the README table."""
    for line in block.splitlines():
        stripped = line.strip()
        if stripped.startswith(f"| {metric} |"):
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            if len(cells) >= 2:
                return cells[1]
    return None


def _check_readme(
    readme_path: Path, summary: dict[str, Any], metadata: dict[str, Any]
) -> list[str]:
    """Confirm the README benchmark block matches the JSON it is generated from."""
    text = readme_path.read_text(encoding="utf-8")
    if _START_MARKER not in text or _END_MARKER not in text:
        raise IntegrityError(
            f"README {readme_path} is missing the {_START_MARKER}/{_END_MARKER} block"
        )
    block = text.split(_START_MARKER, 1)[1].split(_END_MARKER, 1)[0]

    errors: list[str] = []
    expectations = {
        "Mean ROC-AUC": f"{float(summary['mean_auc']):.4f}",
        "Median ROC-AUC": f"{float(summary['median_auc']):.4f}",
        "Mean Oracle F1": f"{float(summary['mean_oracle_f1']):.4f}",
        "Datasets (successful / total)": f"{summary['successful']} / {summary['total_datasets']}",
    }
    for metric, expected in expectations.items():
        actual = _readme_current_value(block, metric)
        if actual is None:
            errors.append(f"README benchmark block has no '{metric}' row")
        elif actual != expected:
            errors.append(
                f"README '{metric}' Current column is {actual!r} but JSON implies {expected!r}"
            )

    timestamp = str(metadata.get("timestamp", ""))
    if timestamp and timestamp not in block:
        errors.append(f"README benchmark block does not cite the run timestamp {timestamp!r}")
    commit = str(metadata.get("git_commit", ""))
    if commit and not re.search(re.escape(commit[:7]), block):
        errors.append(f"README benchmark block does not cite the run commit {commit[:7]!r}")
    return errors


def check(results_path: Path, readme_path: Path) -> list[str]:
    """Run every integrity check; return the list of violations (empty = clean)."""
    data = _load_results(results_path)
    summary = data["summary"]
    per_dataset = data["per_dataset"]
    metadata = data["metadata"]
    errors: list[str] = []
    errors += _check_structural(summary, per_dataset)
    errors += _check_recomputed_headline(summary, per_dataset)
    errors += _check_readme(readme_path, summary, metadata)
    return errors


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results",
        type=Path,
        default=Path("benchmarks/mercury_benchmark_results.json"),
        help="Path to the benchmark results JSON.",
    )
    parser.add_argument(
        "--readme",
        type=Path,
        default=Path("README.md"),
        help="Path to README.md carrying the benchmark block.",
    )
    args = parser.parse_args(argv)

    try:
        violations = check(args.results, args.readme)
    except IntegrityError as exc:
        print(f"ERROR: benchmark integrity gate could not run: {exc}", file=sys.stderr)
        return 2

    if violations:
        print("ERROR: benchmark integrity violations:", file=sys.stderr)
        for violation in violations:
            print(f"  - {violation}", file=sys.stderr)
        print(
            "\nRegenerate the README block "
            "(python scripts/update_readme_benchmarks.py) or re-run the benchmark "
            "pipeline; do not loosen this gate.",
            file=sys.stderr,
        )
        return 1

    print(
        "benchmark integrity OK: "
        f"{args.results} summary is internally consistent, the headline AUC/F1 "
        "recomputes from per_dataset, and README matches."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
