"""Render the plain Prometheus rule file and the Helm rule template from the CRD.

``monitoring/prometheus/prometheus-rules.yaml`` is a Prometheus Operator
``PrometheusRule`` object (``apiVersion``/``kind``/``spec.groups``) for
Kubernetes. A stand-alone Prometheus -- the docker-compose stack -- cannot load
that file: ``promtool check config`` rejects it with ``field apiVersion not
found in type rulefmt.RuleGroups`` and Prometheus refuses to start. This
script writes ``spec.groups`` out as the plain ``groups:`` file
(``monitoring/prometheus/rules.yml``) that ``prometheus.yml`` loads, and as the
Helm chart's ``templates/prometheusrule.yaml`` (alert templates escaped from
Helm, the namespace taken from the release, operator custom rules appended),
so the CRD is the single source of truth for compose, raw manifests and Helm.

Usage:
    python scripts/render_prometheus_rules.py           # rewrite rules.yml
    python scripts/render_prometheus_rules.py --check   # exit 1 on drift

Exit codes:
    0  Both files written (or, with --check, already current).
    1  --check found a file out of date.
    2  The CRD is missing or has no spec.groups.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "monitoring" / "prometheus" / "prometheus-rules.yaml"
TARGET = REPO_ROOT / "monitoring" / "prometheus" / "rules.yml"
HELM_TARGET = REPO_ROOT / "helm" / "mercury-agent" / "templates" / "prometheusrule.yaml"

HEADER = (
    "# GENERATED by scripts/render_prometheus_rules.py from prometheus-rules.yaml\n"
    "# (the PrometheusRule CRD's spec.groups). Do not edit by hand: edit the CRD\n"
    "# and re-run the script. CI fails when this file drifts from the CRD.\n"
)


class _BlockDumper(yaml.SafeDumper):  # type: ignore[misc, unused-ignore]
    """SafeDumper that writes multi-line strings (PromQL, descriptions) as ``|`` blocks."""


def _str_representer(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_BlockDumper.add_representer(str, _str_representer)


HELM_HEADER = (
    "{{- /*\n"
    "GENERATED by scripts/render_prometheus_rules.py from\n"
    "monitoring/prometheus/prometheus-rules.yaml (the PrometheusRule CRD's spec.groups).\n"
    "Do not edit by hand: edit the CRD and re-run the script. CI fails on drift.\n"
    'Every rule selects {app="mercury-agent"}; servicemonitor.yaml attaches it.\n'
    "*/}}\n"
)

#: The namespace the raw manifests hard-code; Helm uses the release's instead.
_RAW_NAMESPACE = 'namespace="mercury-agent"'
_HELM_NAMESPACE = 'namespace="{{ include "mercury-agent.namespace" . }}"'


def _groups(crd_text: str) -> list[Any]:
    doc: Any = yaml.safe_load(crd_text)
    groups = doc.get("spec", {}).get("groups") if isinstance(doc, dict) else None
    if not isinstance(groups, list) or not groups:
        raise ValueError("PrometheusRule has no spec.groups to render")
    return groups


def _dump(payload: Any) -> str:
    text: str = yaml.dump(
        payload,
        Dumper=_BlockDumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=1000,
    )
    return text


def render(crd_text: str) -> str:
    """Return the plain rule-file text for a PrometheusRule CRD document."""
    return HEADER + _dump({"groups": _groups(crd_text)})


def _helm_escape(text: str) -> str:
    """Make Prometheus ``{{ ... }}`` templates literal under Helm's renderer."""
    return re.sub(r"\{\{(.*?)\}\}", lambda m: "{{ `{{" + m.group(1) + "}}` }}", text)


def render_helm(crd_text: str) -> str:
    """Return the Helm ``prometheusrule.yaml`` template for a PrometheusRule CRD document."""
    body = _helm_escape(_dump(_groups(crd_text))).replace(_RAW_NAMESPACE, _HELM_NAMESPACE)
    indented = "".join(f"    {line}" if line.strip() else line for line in body.splitlines(True))
    return (
        HELM_HEADER
        + "{{- if and .Values.metrics.enabled .Values.metrics.prometheusRule.enabled }}\n"
        + "apiVersion: monitoring.coreos.com/v1\n"
        + "kind: PrometheusRule\n"
        + "metadata:\n"
        + '  name: {{ include "mercury-agent.fullname" . }}-rules\n'
        + '  namespace: {{ include "mercury-agent.namespace" . }}\n'
        + "  labels:\n"
        + '    {{- include "mercury-agent.labels" . | nindent 4 }}\n'
        + "spec:\n"
        + "  groups:\n"
        + indented
        + "{{- with .Values.metrics.prometheusRule.rules }}\n"
        + "    - name: mercury-agent.custom\n"
        + "      rules:\n"
        + "        {{- toYaml . | nindent 8 }}\n"
        + "{{- end }}\n"
        + "{{- end }}\n"
    )


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if either output is stale")
    args = parser.parse_args(argv)

    try:
        crd = SOURCE.read_text(encoding="utf-8")
        outputs = ((TARGET, render(crd)), (HELM_TARGET, render_helm(crd)))
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    stale = [
        target
        for target, rendered in outputs
        if (target.read_text(encoding="utf-8") if target.exists() else None) != rendered
    ]
    if args.check:
        for target in stale:
            print(
                f"{target.relative_to(REPO_ROOT)} is out of date with "
                f"{SOURCE.relative_to(REPO_ROOT)}; run scripts/render_prometheus_rules.py",
                file=sys.stderr,
            )
        return 1 if stale else 0
    for target, rendered in outputs:
        if target in stale:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(rendered, encoding="utf-8")
            print(f"wrote {target.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
