class HierarchicalPredictiveCoder:
    """
    Hierarchical predictive coding network.

    Implements multi-level predictions where each level
    predicts the activity of the level below.
    """

    def __init__(
        self,
        input_dim: int,
        hidden_dims: list[int] | None = None,
        learning_rate: float = DEFAULT_LEARNING_RATE,
    ):
        """Initialize hierarchical predictive coder.

        Args:
            input_dim: Input dimension (sensory level)
            hidden_dims: Dimensions for each hidden level
            learning_rate: Learning rate for updates
        """
        self.input_dim = input_dim
        self.hidden_dims = hidden_dims or [64, 32, 16]
        self.learning_rate = learning_rate

        # Build hierarchy
        self.levels = list(ProcessingLevel)[: len(self.hidden_dims) + 1]
        self.models: dict[ProcessingLevel, GenerativeModel] = {}
        self.beliefs: dict[ProcessingLevel, BeliefState] = {}

        self._build_hierarchy()

        # Precision estimator
        self.precision_estimator = PrecisionEstimator()

        # Error tracking
        self._error_counter = 0
        self._prediction_counter = 0

        logger.info(f"HierarchicalPredictiveCoder initialized (levels={len(self.levels)})")

    def _build_hierarchy(self) -> None:
        """Build the predictive hierarchy."""
        np.random.seed(42)

        dims = [self.input_dim] + self.hidden_dims

        for i, level in enumerate(self.levels):
            if i > 0:
                # Generative model from level i to level i-1
                input_dim = dims[i]
                output_dim = dims[i - 1]

                scale = np.sqrt(2.0 / (input_dim + output_dim))
                self.models[level] = GenerativeModel(
                    level=level,
                    weights=np.random.randn(input_dim, output_dim) * scale,
                    bias=np.zeros(output_dim),
                    learning_rate=self.learning_rate,
                )

            # Belief state for this level
            self.beliefs[level] = BeliefState(
                level=level,
                mean=np.zeros(dims[i]),
                variance=np.ones(dims[i]),
            )

    def process(
        self,
        observation: np.ndarray,
        update_beliefs: bool = True,
    ) -> tuple[list[PredictionError], FreeEnergy]:
        """Process an observation through the hierarchy.

        Args:
            observation: Input observation
            update_beliefs: Whether to update beliefs

        Returns:
            Tuple of (prediction_errors, free_energy)
        """
        prediction_errors: list[PredictionError] = []
        total_pe_magnitude = 0.0

        # Bottom-up pass: compute prediction errors
        current_input = observation

        for i, level in enumerate(self.levels):
            if i == 0:
                # Sensory level: compare with prediction from above
                if i + 1 < len(self.levels):
                    higher_level = self.levels[i + 1]
                    if higher_level in self.models:
                        prediction = self.models[higher_level].predict(
                            self.beliefs[higher_level].mean
                        )
                    else:
                        prediction = np.zeros_like(observation)
                else:
                    prediction = np.zeros_like(observation)

                error = self._compute_error(level, prediction, observation)
                prediction_errors.append(error)
                total_pe_magnitude += error.magnitude

                current_input = error.error

            else:
                # Higher levels: encode prediction error from below
                if update_beliefs:
                    self._update_belief(level, current_input)

                # Compute prediction error at this level
                if i + 1 < len(self.levels):
                    higher_level = self.levels[i + 1]
                    if higher_level in self.models:
                        prediction = self.models[higher_level].predict(
                            self.beliefs[higher_level].mean
                        )
                    else:
                        prediction = np.zeros_like(self.beliefs[level].mean)

                    error = self._compute_error(level, prediction, self.beliefs[level].mean)
                    prediction_errors.append(error)
                    total_pe_magnitude += error.magnitude

                    current_input = error.error

        # Top-down pass: update generative models
        if update_beliefs:
            self._update_models(prediction_errors)

        # Compute free energy
        free_energy = self._compute_free_energy(prediction_errors)

        return prediction_errors, free_energy

    def predict(
        self,
        steps_ahead: int = 1,
    ) -> list[Prediction]:
        """Generate predictions for future observations.

        Args:
            steps_ahead: Number of steps to predict

        Returns:
            List of predictions
        """
        predictions: list[Prediction] = []

        for _ in range(steps_ahead):
            self._prediction_counter += 1
            prediction_id = f"pred_{self._prediction_counter:06d}"

            # Propagate beliefs down the hierarchy
            for i in range(len(self.levels) - 1, 0, -1):
                level = self.levels[i]
                lower_level = self.levels[i - 1]

                if level in self.models:
                    predicted_value = self.models[level].predict(self.beliefs[level].mean)

                    precision = self.precision_estimator.get_precision(lower_level)

                    prediction = Prediction(
                        prediction_id=f"{prediction_id}_{lower_level.value}",
                        prediction_type=PredictionType.STATE,
                        level=lower_level,
                        value=predicted_value,
                        precision=precision,
                    )
                    predictions.append(prediction)

        return predictions

    def _compute_error(
        self,
        level: ProcessingLevel,
        prediction: np.ndarray,
        observation: np.ndarray,
    ) -> PredictionError:
        """Compute prediction error at a level."""
        self._error_counter += 1
        error_id = f"pe_{self._error_counter:06d}"

        error = observation - prediction
        precision = self.precision_estimator.get_precision(level)
        precision_weighted_error = precision * error

        magnitude = float(np.sqrt(np.mean(error**2)))

        # Update precision estimate
        self.precision_estimator.update_precision(level, magnitude)

        # Determine if anomaly
        is_anomaly = magnitude > 2.0 / np.sqrt(precision + 1e-8)

        return PredictionError(
            error_id=error_id,
            level=level,
            prediction=prediction,
            observation=observation,
            error=error,
            precision_weighted_error=precision_weighted_error,
            magnitude=magnitude,
            is_anomaly=is_anomaly,
        )

    def _update_belief(
        self,
        level: ProcessingLevel,
        bottom_up_signal: np.ndarray,
    ) -> None:
        """Update belief at a level."""
        belief = self.beliefs[level]

        # Get top-down prediction
        level_idx = self.levels.index(level)
        if level_idx + 1 < len(self.levels):
            higher_level = self.levels[level_idx + 1]
            if higher_level in self.models:
                top_down_prediction = self.models[higher_level].predict(
                    self.beliefs[higher_level].mean
                )
            else:
                top_down_prediction = np.zeros_like(belief.mean)
        else:
            top_down_prediction = np.zeros_like(belief.mean)

        # Precision-weighted combination of bottom-up and top-down
        bottom_up_precision = self.precision_estimator.get_precision(
            self.levels[level_idx - 1] if level_idx > 0 else level
        )
        top_down_precision = self.precision_estimator.get_precision(level)

        total_precision = bottom_up_precision + top_down_precision + 1e-8

        # Resize signals if needed
        if len(bottom_up_signal) != len(belief.mean):
            # Project or truncate
            if len(bottom_up_signal) > len(belief.mean):
                bottom_up_signal = bottom_up_signal[: len(belief.mean)]
            else:
                bottom_up_signal = np.pad(
                    bottom_up_signal,
                    (0, len(belief.mean) - len(bottom_up_signal)),
                )

        if len(top_down_prediction) != len(belief.mean):
            if len(top_down_prediction) > len(belief.mean):
                top_down_prediction = top_down_prediction[: len(belief.mean)]
            else:
                top_down_prediction = np.pad(
                    top_down_prediction,
                    (0, len(belief.mean) - len(top_down_prediction)),
                )

        # Update mean
        new_mean = (
            bottom_up_precision * bottom_up_signal + top_down_precision * top_down_prediction
        ) / total_precision

        belief.mean = (1 - self.learning_rate) * belief.mean + self.learning_rate * new_mean
        belief.timestamp = time.time()

    def _update_models(self, errors: list[PredictionError]) -> None:
        """Update generative models based on prediction errors."""
        for error in errors:
            level_idx = self.levels.index(error.level)
            if level_idx + 1 < len(self.levels):
                higher_level = self.levels[level_idx + 1]
                if higher_level in self.models:
                    self.models[higher_level].update(
                        error.error,
                        self.beliefs[higher_level].mean,
                    )

    def _compute_free_energy(
        self,
        errors: list[PredictionError],
    ) -> FreeEnergy:
        """Compute free energy from prediction errors."""
        # Prediction error term: sum of precision-weighted squared errors
        pe_term = sum(0.5 * np.sum(e.precision_weighted_error**2) for e in errors)

        # Complexity term: KL divergence from prior
        complexity_term = 0.0
        for level, belief in self.beliefs.items():
            # Assume standard normal prior
            complexity_term += 0.5 * np.sum(
                belief.mean**2 + belief.variance - 1 - np.log(belief.variance + 1e-8)
            )

        total = pe_term + complexity_term

        return FreeEnergy(
            total=float(total),
            prediction_error_term=float(pe_term),
            complexity_term=float(complexity_term),
        )


