class PrecisionEstimator:
    """
    Estimates precision (inverse variance) of predictions.

    Precision weighting is crucial for properly combining
    predictions and observations.
    """

    def __init__(
        self,
        initial_precision: float = DEFAULT_PRECISION,
        learning_rate: float = 0.1,
        min_precision: float = 0.01,
        max_precision: float = 100.0,
    ):
        """Initialize precision estimator.

        Args:
            initial_precision: Initial precision value
            learning_rate: Learning rate for updates
            min_precision: Minimum allowed precision
            max_precision: Maximum allowed precision
        """
        self.learning_rate = learning_rate
        self.min_precision = min_precision
        self.max_precision = max_precision

        # Precision for each level
        self._precisions: dict[ProcessingLevel, float] = dict.fromkeys(
            ProcessingLevel, initial_precision
        )

        # Running error statistics
        self._error_history: dict[ProcessingLevel, deque[float]] = {
            level: deque(maxlen=100) for level in ProcessingLevel
        }

    def get_precision(self, level: ProcessingLevel) -> float:
        """Get precision for a level."""
        return self._precisions[level]

    def estimate(
        self,
        errors: np.ndarray,
    ) -> np.ndarray:
        """Estimate precisions for an array of errors (simplified API).

        Args:
            errors: Array of prediction errors

        Returns:
            Array of precision values (inverse variance)
        """
        errors = np.asarray(errors)

        # Compute local variance using sliding window
        window_size = min(10, len(errors))
        precisions = np.zeros_like(errors, dtype=float)

        for i in range(len(errors)):
            start = max(0, i - window_size // 2)
            end = min(len(errors), i + window_size // 2 + 1)
            local_errors = errors[start:end]

            # Variance with small epsilon for stability
            variance = np.var(local_errors) + 1e-8

            # Precision is inverse variance, clipped to reasonable range
            precision = 1.0 / variance
            precisions[i] = np.clip(precision, self.min_precision, self.max_precision)

        return precisions

    def update_precision(
        self,
        level: ProcessingLevel,
        error_magnitude: float,
    ) -> float:
        """Update precision based on error magnitude.

        Args:
            level: Processing level
            error_magnitude: Magnitude of prediction error

        Returns:
            Updated precision
        """
        # Store error
        self._error_history[level].append(error_magnitude)

        if len(self._error_history[level]) < 10:
            return self._precisions[level]

        # Estimate variance from recent errors
        errors = np.array(self._error_history[level])
        estimated_variance = np.var(errors) + 1e-8

        # Update precision (inverse variance)
        target_precision = 1.0 / estimated_variance
        target_precision = np.clip(target_precision, self.min_precision, self.max_precision)

        # Exponential moving average
        self._precisions[level] = (1 - self.learning_rate) * self._precisions[
            level
        ] + self.learning_rate * target_precision

        return self._precisions[level]


