# Data Structures
# =============================================================================


@dataclass
class Prediction:
    """A prediction generated by the model.

    Attributes:
        prediction_id: Unique identifier
        prediction_type: Type of prediction
        level: Processing level
        value: Predicted value(s)
        precision: Confidence/precision of prediction
        timestamp: Generation timestamp
        metadata: Additional metadata
    """

    prediction_id: str
    prediction_type: PredictionType
    level: ProcessingLevel
    value: np.ndarray
    precision: float = DEFAULT_PRECISION
    timestamp: float = field(default_factory=time.time)
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class PredictionError:
    """Error between prediction and observation.

    Attributes:
        error_id: Unique identifier
        level: Processing level where error occurred
        prediction: Original prediction
        observation: Actual observation
        error: Error value (observation - prediction)
        precision_weighted_error: Error weighted by precision
        magnitude: Error magnitude
        is_anomaly: Whether error indicates anomaly
        timestamp: Detection timestamp
    """

    error_id: str
    level: ProcessingLevel
    prediction: np.ndarray
    observation: np.ndarray
    error: np.ndarray
    precision_weighted_error: np.ndarray
    magnitude: float
    is_anomaly: bool = False
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> dict[str, Any]:
        """Convert to dictionary."""
        return {
            "id": self.error_id,
            "level": self.level.value,
            "magnitude": self.magnitude,
            "is_anomaly": self.is_anomaly,
        }


@dataclass
class GenerativeModel:
    """A generative model at one level of hierarchy.

    Attributes:
        level: Processing level
        weights: Model weights
        bias: Model bias
        precision: Output precision
        learning_rate: Learning rate for updates
    """

    level: ProcessingLevel
    weights: np.ndarray
    bias: np.ndarray
    precision: float = DEFAULT_PRECISION
    learning_rate: float = DEFAULT_LEARNING_RATE

    def predict(self, higher_level_state: np.ndarray) -> np.ndarray:
        """Generate prediction from higher-level state."""
        return higher_level_state @ self.weights + self.bias

    def update(self, error: np.ndarray, higher_level_state: np.ndarray) -> None:
        """Update weights based on prediction error."""
        # Gradient descent on prediction error
        grad_weights = np.outer(higher_level_state, error)
        grad_bias = error

        self.weights -= self.learning_rate * grad_weights
        self.bias -= self.learning_rate * grad_bias


@dataclass
class BeliefState:
    """Internal belief state at a hierarchy level.

    Attributes:
        level: Processing level
        mean: Belief mean (expected state)
        variance: Belief variance (uncertainty)
        precision: Inverse variance
        timestamp: Last update timestamp
    """

    level: ProcessingLevel
    mean: np.ndarray
    variance: np.ndarray
    precision: np.ndarray = field(default_factory=lambda: np.array([]))
    timestamp: float = field(default_factory=time.time)

    def __post_init__(self) -> None:
        if len(self.precision) == 0:
            self.precision = 1.0 / (self.variance + 1e-8)


@dataclass
class FreeEnergy:
    """Free energy computation result.

    Attributes:
        total: Total free energy
        prediction_error_term: Contribution from prediction errors
        complexity_term: Contribution from model complexity
        surprise: Negative log probability of observations
        entropy: Entropy of beliefs
    """

    total: float
    prediction_error_term: float
    complexity_term: float
    surprise: float = 0.0
    entropy: float = 0.0


# =============================================================================
# Precision Estimator
# =============================================================================


class PrecisionEstimator:
    """
    Estimates precision (inverse variance) of predictions.

    Precision weighting is crucial for properly combining
    predictions and observations.
    """

    def __init__(
        self,
        initial_precision: float = DEFAULT_PRECISION,
        learning_rate: float = 0.1,
        min_precision: float = 0.01,
        max_precision: float = 100.0,
    ):
        """Initialize precision estimator.

        Args:
            initial_precision: Initial precision value
            learning_rate: Learning rate for updates
            min_precision: Minimum allowed precision
            max_precision: Maximum allowed precision
        """
        self.learning_rate = learning_rate
        self.min_precision = min_precision
        self.max_precision = max_precision

        # Precision for each level
        self._precisions: dict[ProcessingLevel, float] = dict.fromkeys(
            ProcessingLevel, initial_precision
        )

        # Running error statistics
        self._error_history: dict[ProcessingLevel, deque[float]] = {
            level: deque(maxlen=100) for level in ProcessingLevel
        }

    def get_precision(self, level: ProcessingLevel) -> float:
        """Get precision for a level."""
        return self._precisions[level]

    def update_precision(
        self,
        level: ProcessingLevel,
        error_magnitude: float,
    ) -> float:
        """Update precision based on error magnitude.

        Args:
            level: Processing level
            error_magnitude: Magnitude of prediction error

        Returns:
            Updated precision
        """
        # Store error
        self._error_history[level].append(error_magnitude)

        if len(self._error_history[level]) < 10:
            return self._precisions[level]

        # Estimate variance from recent errors
        errors = np.array(self._error_history[level])
        estimated_variance = np.var(errors) + 1e-8

        # Update precision (inverse variance)
        target_precision = 1.0 / estimated_variance
        target_precision = np.clip(target_precision, self.min_precision, self.max_precision)

        # Exponential moving average
        self._precisions[level] = (1 - self.learning_rate) * self._precisions[
            level
        ] + self.learning_rate * target_precision

        return self._precisions[level]


