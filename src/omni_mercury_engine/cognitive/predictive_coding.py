class PredictiveCodingDetector:
    """
    Anomaly detector based on predictive coding principles.

    Detects anomalies as observations that generate large
    prediction errors that cannot be explained away.
    """

    def __init__(
        self,
        input_dim: int,
        hidden_dims: list[int] | None = None,
        anomaly_threshold: float = 2.0,
        learning_rate: float = DEFAULT_LEARNING_RATE,
    ):
        """Initialize predictive coding detector.

        Args:
            input_dim: Input dimension
            hidden_dims: Hidden layer dimensions
            anomaly_threshold: Threshold for anomaly detection
            learning_rate: Learning rate
        """
        self.input_dim = input_dim
        self.anomaly_threshold = anomaly_threshold

        # Predictive hierarchy
        self.coder = HierarchicalPredictiveCoder(
            input_dim=input_dim,
            hidden_dims=hidden_dims,
            learning_rate=learning_rate,
        )

        # Statistics
        self._detection_counter = 0
        self._stats = {
            "detections": 0,
            "anomalies_detected": 0,
            "avg_prediction_error": 0.0,
            "avg_free_energy": 0.0,
        }

        logger.info(f"PredictiveCodingDetector initialized (threshold={anomaly_threshold})")

    def detect(
        self,
        observation: np.ndarray,
        update_model: bool = True,
    ) -> dict[str, Any]:
        """Detect anomalies in observation.

        Args:
            observation: Input observation
            update_model: Whether to update the model

        Returns:
            Detection result
        """
        self._detection_counter += 1

        # Process through hierarchy
        errors, free_energy = self.coder.process(observation, update_beliefs=update_model)

        # Calculate overall anomaly score
        total_error = sum(e.magnitude for e in errors)
        avg_error = total_error / len(errors) if errors else 0.0

        # Anomaly score based on free energy and prediction error
        anomaly_score = self._compute_anomaly_score(errors, free_energy)

        # Determine if anomaly
        is_anomaly = anomaly_score > self.anomaly_threshold
        any_level_anomaly = any(e.is_anomaly for e in errors)

        # Update statistics
        self._stats["detections"] += 1
        if is_anomaly:
            self._stats["anomalies_detected"] += 1

        n = self._stats["detections"]
        self._stats["avg_prediction_error"] = (
            self._stats["avg_prediction_error"] * (n - 1) + avg_error
        ) / n
        self._stats["avg_free_energy"] = (
            self._stats["avg_free_energy"] * (n - 1) + free_energy.total
        ) / n

        return {
            "detection_id": f"pc_det_{self._detection_counter:06d}",
            "anomaly_score": float(anomaly_score),
            "is_anomaly": is_anomaly or any_level_anomaly,
            "confidence": 1.0 - np.exp(-anomaly_score),
            "free_energy": free_energy.total,
            "prediction_error": avg_error,
            "level_errors": [e.to_dict() for e in errors],
            "anomalous_levels": [e.level.value for e in errors if e.is_anomaly],
        }

    def _compute_anomaly_score(
        self,
        errors: list[PredictionError],
        free_energy: FreeEnergy,
    ) -> float:
        """Compute anomaly score from errors and free energy."""
        # Weight errors by level (lower levels = more important)
        weighted_error = 0.0
        total_weight = 0.0

        for i, error in enumerate(errors):
            weight = 1.0 / (i + 1)  # Higher weight for lower levels
            weighted_error += weight * error.magnitude
            total_weight += weight

        if total_weight > 0:
            avg_weighted_error = weighted_error / total_weight
        else:
            avg_weighted_error = 0.0

        # Combine with free energy
        fe_contribution = free_energy.prediction_error_term / (len(errors) + 1)

        return float(avg_weighted_error + 0.1 * fe_contribution)

    def fit(
        self,
        data: np.ndarray,
        epochs: int = 10,
    ) -> dict[str, list[float]]:
        """Fit the model to data.

        Args:
            data: Training data (n_samples, input_dim)
            epochs: Number of training epochs

        Returns:
            Training history
        """
        history = {"free_energy": [], "prediction_error": []}

        for epoch in range(epochs):
            epoch_fe = []
            epoch_pe = []

            for observation in data:
                errors, free_energy = self.coder.process(observation, update_beliefs=True)
                epoch_fe.append(free_energy.total)
                epoch_pe.append(np.mean([e.magnitude for e in errors]))

            history["free_energy"].append(float(np.mean(epoch_fe)))
            history["prediction_error"].append(float(np.mean(epoch_pe)))

            logger.info(
                f"Epoch {epoch + 1}/{epochs}: FE={history['free_energy'][-1]:.4f}, "
                f"PE={history['prediction_error'][-1]:.4f}"
            )

        return history

    def get_predictions(self, steps: int = 1) -> list[Prediction]:
        """Get future predictions.

        Args:
            steps: Steps to predict ahead

        Returns:
            List of predictions
        """
        return self.coder.predict(steps)

    def get_statistics(self) -> dict[str, Any]:
        """Get detector statistics."""
        return {
            **self._stats,
            "anomaly_threshold": self.anomaly_threshold,
            "input_dim": self.input_dim,
            "hierarchy_depth": len(self.coder.levels),
        }


