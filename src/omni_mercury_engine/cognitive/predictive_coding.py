# Integration with Mercury Agent
# =============================================================================


class MercuryPredictiveCoding:
    """
    Predictive coding integration for Mercury Agent.

    Provides neuroscience-inspired anomaly detection
    as part of the Mercury Agent framework.
    """

    def __init__(
        self,
        input_dim: int = 64,
        hidden_dims: list[int] | None = None,
        anomaly_threshold: float = 2.0,
        enable_active_inference: bool = True,
    ):
        """Initialize Mercury predictive coding.

        Args:
            input_dim: Input dimension
            hidden_dims: Hidden layer dimensions
            anomaly_threshold: Anomaly detection threshold
            enable_active_inference: Enable active inference actions
        """
        self.detector = PredictiveCodingDetector(
            input_dim=input_dim,
            hidden_dims=hidden_dims,
            anomaly_threshold=anomaly_threshold,
        )

        self.enable_active_inference = enable_active_inference

        if enable_active_inference:
            self.agent = ActiveInferenceAgent(
                self.detector.coder,
                action_dim=4,  # investigate, monitor, alert, ignore
            )

        # Action names
        self._actions = ["investigate", "monitor", "alert", "ignore"]

    def analyze(
        self,
        features: np.ndarray,
        return_action: bool = False,
    ) -> dict[str, Any]:
        """Analyze features for anomalies.

        Args:
            features: Input features
            return_action: Whether to return recommended action

        Returns:
            Analysis result
        """
        # Detect anomaly
        detection = self.detector.detect(features)

        result = {
            "anomaly_score": detection["anomaly_score"],
            "is_anomaly": detection["is_anomaly"],
            "confidence": detection["confidence"],
            "free_energy": detection["free_energy"],
            "prediction_error": detection["prediction_error"],
        }

        # Get recommended action via active inference
        if return_action and self.enable_active_inference:
            action_idx, expected_fe = self.agent.select_action(features)
            result["recommended_action"] = self._actions[action_idx]
            result["action_confidence"] = np.exp(-expected_fe)

        return result

    def train(
        self,
        data: np.ndarray,
        epochs: int = 10,
    ) -> dict[str, list[float]]:
        """Train the predictive model.

        Args:
            data: Training data
            epochs: Training epochs

        Returns:
            Training history
        """
        return self.detector.fit(data, epochs)

    def get_statistics(self) -> dict[str, Any]:
        """Get module statistics."""
        return {
            "detector": self.detector.get_statistics(),
            "active_inference_enabled": self.enable_active_inference,
        }
