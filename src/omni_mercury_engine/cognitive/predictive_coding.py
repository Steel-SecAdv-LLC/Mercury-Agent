from __future__ import annotations


"""
Predictive Coding Module for Mercury Agent.

Implements neuroscience-inspired predictive coding for anomaly detection,
based on:
- "Predictive Coding" (Rao & Ballard, 1999)
- "The Free Energy Principle" (Friston, 2010)
- "Hierarchical Predictive Coding" (Spratling, 2017)
- "Active Inference for Anomaly Detection" (Parr & Friston, 2019)

Predictive coding theory suggests the brain minimizes prediction errors
by maintaining hierarchical generative models that predict sensory input.
Anomalies correspond to large prediction errors that cannot be explained
away.

Key Concepts:
- Prediction: Generate expected observations
- Prediction Error: Difference between prediction and observation
- Precision Weighting: Confidence in predictions
- Hierarchical Processing: Multi-level predictions
- Active Inference: Action selection to minimize surprise

This module uses these principles for biologically-inspired
anomaly detection in Mercury Agent.
"""

import logging
import time
from collections import deque
from dataclasses import dataclass, field
from enum import Enum
from typing import Any

import numpy as np


logger = logging.getLogger(__name__)


# =============================================================================
# Constants
# =============================================================================

PHI = (1 + np.sqrt(5)) / 2  # Golden ratio

# Predictive coding parameters
DEFAULT_LEARNING_RATE = 0.01
DEFAULT_PRECISION = 1.0
MAX_HIERARCHY_DEPTH = 5
PREDICTION_HORIZON = 10


class ProcessingLevel(Enum):
    """Levels in the predictive hierarchy."""

    SENSORY = "sensory"  # Raw sensory data
    FEATURE = "feature"  # Feature extraction
    OBJECT = "object"  # Object recognition
    CONTEXT = "context"  # Contextual understanding
    ABSTRACT = "abstract"  # Abstract concepts


class UpdateMode(Enum):
    """Modes for belief updating."""

    PREDICTIVE = "predictive"  # Standard predictive coding
    ACTIVE = "active"  # Active inference
    HIERARCHICAL = "hierarchical"  # Hierarchical updates
    FREE_ENERGY = "free_energy"  # Free energy minimization


class PredictionType(Enum):
    """Types of predictions."""

    STATE = "state"  # State prediction
    OBSERVATION = "observation"  # Observation prediction
    ACTION = "action"  # Action prediction
    PRECISION = "precision"  # Precision prediction


