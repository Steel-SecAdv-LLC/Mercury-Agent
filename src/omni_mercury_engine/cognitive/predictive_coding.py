class ActiveInferenceAgent:
    """
    Active inference agent for anomaly detection.

    Implements active inference principles where the agent
    selects actions to minimize expected free energy.
    """

    def __init__(
        self,
        predictive_coder: HierarchicalPredictiveCoder | None = None,
        action_dim: int = 4,
        state_dim: int | None = None,
    ):
        """Initialize active inference agent.

        Args:
            predictive_coder: Predictive coding network (optional)
            action_dim: Number of available actions
            state_dim: State dimension (creates internal predictive coder if provided)
        """
        # Handle state_dim parameter (test API)
        if predictive_coder is None and state_dim is not None:
            self.predictive_coder = HierarchicalPredictiveCoder(
                input_dim=state_dim,
                num_levels=2,
            )
        elif predictive_coder is not None:
            self.predictive_coder = predictive_coder
        else:
            self.predictive_coder = HierarchicalPredictiveCoder(input_dim=10, num_levels=2)

        self.action_dim = action_dim
        self.state_dim = state_dim or self.predictive_coder.input_dim

        # Action preferences (prior expectations)
        self.action_prior = np.ones(action_dim) / action_dim

        # Action-outcome model
        self._action_outcomes: dict[int, list[float]] = {i: [] for i in range(action_dim)}

    def select_action(
        self,
        observation_or_state: np.ndarray,
        available_actions: list[dict[str, Any]] | None = None,
        planning_horizon: int = 5,
    ) -> dict[str, Any] | tuple[int, float]:
        """Select action to minimize expected free energy.

        Args:
            observation_or_state: Current observation/state
            available_actions: List of available action dicts (test API)
            planning_horizon: Planning horizon

        Returns:
            Selected action (dict if available_actions provided, else tuple)
        """
        observation = np.asarray(observation_or_state)

        # Handle available_actions parameter (test API)
        if available_actions is not None:
            # Evaluate expected free energy for each available action
            best_action = available_actions[0]
            best_fe = float("inf")

            for candidate_action in available_actions:
                # Simplified expected free energy computation
                expected_fe = self._compute_action_fe(observation, candidate_action)
                if expected_fe < best_fe:
                    best_fe = expected_fe
                    best_action = candidate_action

            return best_action

        # Original API
        errors, current_fe = self.predictive_coder.process(observation)

        # Evaluate expected free energy for each action
        expected_fes = []

        for action in range(self.action_dim):
            # Simulate action consequences (simplified)
            expected_fe = self._expected_free_energy(action, errors, planning_horizon)
            expected_fes.append(expected_fe)

        # Select action with minimum expected free energy
        expected_fes_arr = np.array(expected_fes)
        selected_action = int(np.argmin(expected_fes_arr))

        return selected_action, float(expected_fes_arr[selected_action])

    def _compute_action_fe(
        self,
        state: np.ndarray,
        action: dict[str, Any],
    ) -> float:
        """Compute expected free energy for an action dict."""
        action_params = action.get("params", np.zeros(self.action_dim))
        if isinstance(action_params, list):
            action_params = np.array(action_params)

        # Simple heuristic: prefer actions that reduce state magnitude
        state_magnitude = np.sum(state**2)
        action_magnitude = np.sum(action_params**2)

        return float(state_magnitude + 0.1 * action_magnitude)

    def _expected_free_energy(
        self,
        action: int,
        current_errors: list[PredictionError],
        horizon: int,
    ) -> float:
        """Compute expected free energy for an action.

        Expected free energy = Expected surprise + Expected divergence from preferences
        """
        # Estimate expected prediction error reduction
        avg_error = np.mean([e.magnitude for e in current_errors])

        # Historical action effectiveness
        if self._action_outcomes[action]:
            effectiveness = float(np.mean(self._action_outcomes[action]))
        else:
            effectiveness = 0.5

        # Expected surprise (lower effectiveness = higher surprise)
        expected_surprise = avg_error * (1 - effectiveness)

        # Divergence from action prior (prefer more common actions)
        prior_divergence = -np.log(self.action_prior[action] + 1e-8)

        return float(expected_surprise + 0.1 * prior_divergence)

    def update_from_outcome(
        self,
        action: int,
        observation: np.ndarray,
        success: bool,
    ) -> None:
        """Update models based on action outcome.

        Args:
            action: Action that was taken
            observation: Resulting observation
            success: Whether action was successful
        """
        # Record outcome
        self._action_outcomes[action].append(1.0 if success else 0.0)

        # Keep limited history
        if len(self._action_outcomes[action]) > 100:
            self._action_outcomes[action] = self._action_outcomes[action][-100:]

        # Process observation
        self.predictive_coder.process(observation, update_beliefs=True)


