def test_commands_match_click(catalog: dict[str, Any]) -> None:
    from omni_mercury_engine.cli import main

    expected: dict[str, click.Command] = {}

    def walk(group: click.Group, prefix: str) -> None:
        for name, command in group.commands.items():
            if command.hidden:
                continue
            path = f"{prefix} {name}".strip()
            expected[path] = command
            if isinstance(command, click.Group):
                walk(command, path)

    walk(main, "")
    listed = {c["path"]: c for c in catalog["commands"] if c["path"]}
    assert set(listed) == set(expected)
    for path, command in expected.items():
        options = {
            (
                p.opts[0]
                if not any(f.startswith("--") for f in p.opts)
                else next(f for f in p.opts if f.startswith("--"))
            ): p
            for p in command.params
            if isinstance(p, click.Option) and not p.hidden and p.name != "help"
        }
        row = {o["k"]: o for o in listed[path]["opts"]}
        assert set(row) == set(options), path
        for key, param in options.items():
            entry = row[key]
            assert entry["flags"] == list(param.opts) + list(param.secondary_opts), (path, key)
            assert bool(entry.get("req")) == bool(param.required), (path, key)
            assert bool(entry.get("flag")) == bool(getattr(param, "is_flag", False)), (path, key)
            if isinstance(param.type, click.Choice):
                assert entry["choices"] == [str(c) for c in param.type.choices], (path, key)
            else:
                assert "choices" not in entry, (path, key)


