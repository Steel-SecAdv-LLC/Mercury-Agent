"""The Mercury Console's catalog and scripts agree with the engine they describe.

``static/console/catalog.js`` is generated by ``scripts/build_console_catalog.py``
from the click group, the detector registry, the MCP server, the OpenAPI
document and the loader/hazard modules. These tests pin that:

* the committed catalog is exactly what the generator produces now (a code
  change that alters a command, route or detector without regenerating fails);
* the command table matches click independently of the generator's code path;
* every API path the console's scripts call is served by the app;
* the ``voice --domain`` vocabulary is the sanitizer's whitelist;
* the shipped console scripts obey the page CSP (no eval, no inline style,
  no cross-origin fetch).
"""

