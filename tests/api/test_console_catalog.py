@pytest.mark.skipif(shutil.which("node") is None, reason="node is not installed")
def test_every_chart_renders_without_inline_style(tmp_path: Path) -> None:
    """All chart builders, through ``available()`` and ``render()``, emit CSP-clean SVG."""
    harness = tmp_path / "charts.js"
    harness.write_text(
        """
global.window = { matchMedia: () => ({ matches: false }) };
global.document = { documentElement: {} };
global.getComputedStyle = () => ({ getPropertyValue: () => "" });
require(process.argv[2]);
const V = window.MercuryCLIViz, n = 64;
const s = Array.from({ length: n }, (_, i) => Math.sin(i / 4) + (i === 40 ? 6 : 0));
const shapes = [
  { scores: s.map(Math.abs), anomalies: s.map((v) => Math.abs(v) > 3), threshold: 2.5 },
  { scores: s.map(Math.abs), is_anomaly: s.map((v) => Math.abs(v) > 3), detectors: { a: s, b: s } },
  { contributions: { statistical: 0.5, temporal: 0.3 }, scores: s, anomalies: s.map(() => false) },
];
const req = { data: s.map((v, i) => [v, Math.cos(i), i % 7]) };
const ds = { name: "d.csv", rows: n, cols: 3, names: ["a", "b", "c"], matrix: req.data };
let rendered = 0, bad = 0;
for (const d of shapes) {
  V.available(d, req, ds);
  for (const c of V.CHARTS) {
    const out = V.render(c.id, d, req, ds);
    if (!out) continue;
    rendered++;
    if (/\\sstyle\\s*=|<style/.test(out)) bad++;
  }
}
console.log(JSON.stringify({ rendered, bad }));
""",
        encoding="utf-8",
    )
    result = subprocess.run(
        ["node", str(harness), str(_CONSOLE / "viz.js")],
        capture_output=True,
        text=True,
        timeout=120,
        check=True,
    )
    counts = json.loads(result.stdout.strip().splitlines()[-1])
    assert counts["rendered"] > 20, counts
    assert counts["bad"] == 0, counts


