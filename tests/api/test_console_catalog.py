def test_console_scripts_call_only_served_routes() -> None:
    from omni_mercury_engine.api.server import app

    served = set(app.openapi()["paths"])
    templated = [re.compile("^" + re.sub(r"\\{[^}]+\\}", "[^/]+", p) + "$") for p in served]
    used: set[str] = set()
    for script in _CONSOLE.glob("*.js"):
        if script.name == "catalog.js":
            continue
        used |= set(re.findall(r"""["'](/api/v1/[A-Za-z0-9_./{}-]+)""", script.read_text("utf-8")))
    used = {u.rstrip("/") for u in used if not u.endswith("/")} | {
        u.rstrip("/") for u in used if u.endswith("/")
    }
    unknown = sorted(
        u
        for u in used
        if u not in served and not any(t.match(u) for t in templated) and not u.endswith("/jobs")
    )
    assert used, "no API paths found in the console scripts: the scan is vacuous"
    assert not unknown, f"console scripts call routes this server does not serve: {unknown}"


